const enc = encodeURIComponent;
const notFound = () => Object.assign(new Error('No se encontró este trabajo. Puede que se haya reasignado.'), { status: 404 });
async function getJob(id) {
  const j = store.job(id) || (await store.loadJob(id));
  if (!j) throw store.sync.reachable ? notFound() : new store.Offline();
  return j;
}

// ── PDF: generated by the server (PDFKit); download / native share ──
// Materials and problems are optional: a sheet with switches comes first (the choice is remembered on this phone).
const PDF_PARTS = [['materials', 'Materiales', 'Lista de materiales y su estado'], ['problems', 'Problemas', 'Problemas comunicados, con sus fotos']];
const pdfOpts = () => { try { return { materials: true, problems: true, ...JSON.parse(localStorage.getItem('lcc-pdf-parts') || '{}') }; } catch { return { materials: true, problems: true }; } };
const pdfQuery = (o) => PDF_PARTS.filter(([k]) => o[k] === false).map(([k]) => `${k}=0`).join('&');
const pdfCache = new Map(); // `${job id}?${parts}` -> { stamp, blob: Promise<Blob> } (dropped when the job changes)
function fetchPdf(j, o = pdfOpts()) {
  const key = `${j.id}?${pdfQuery(o)}`, hit = pdfCache.get(key);
  const stamp = JSON.stringify([j.status, j.submittedAt, j.reportGeneratedAt, j.photos, j.materials, j.problems?.length]);
  if (hit?.stamp === stamp) return hit.blob;
  const blob = (async () => {
    const res = await fetch(`/api/jobs/${enc(j.id)}/pdf${pdfQuery(o) ? `?${pdfQuery(o)}` : ''}`).catch(() => null);
    if (!res) throw new store.Offline();
    if (!res.ok) throw new Error('No se pudo generar el informe — inténtalo de nuevo');
    return res.blob();
  })();
  blob.catch(() => pdfCache.delete(key)); // a failed one is tried again next time
  pdfCache.set(key, { stamp, blob });
  return blob;
}
const pdfName = (j) => `LCC-Report-${j.id}.pdf`;
// iPhone home-screen apps can't download from a link (they only open a viewer), so on phones the PDF goes
// to the share sheet ("Guardar en Archivos", WhatsApp, AirDrop…). Elsewhere: a normal download.
export async function downloadPdf(j, o) {
  const blob = await fetchPdf(j, o);
  const file = new File([blob], pdfName(j), { type: 'application/pdf' });
  if (navigator.canShare?.({ files: [file] }) && matchMedia('(pointer: coarse)').matches) {
    const share = () => navigator.share({ files: [file], title: pdfName(j) });
    try { return await share(); } catch (e) { if (e.name === 'AbortError') return; }
    // the tap "expired" while the PDF was being made: one more tap opens the share sheet
    const d = sheet(`<h2>PDF listo</h2><p class="muted">${esc(pdfName(j))} · ${(blob.size / 1048576).toFixed(1)} MB. Toca Guardar PDF y elige “Guardar en Archivos”.</p>
      <div class="sheet-actions"><button class="btn btn-primary" data-save>${icon('download')} Guardar PDF</button><button class="btn btn-secondary" data-close>Cancelar</button></div>`);
    $('[data-save]', d).onclick = async () => { try { await share(); d.close(); } catch (e) { if (e.name === 'AbortError') d.close(); else toast('No se pudo abrir el menú de compartir en este móvil', 'bad'); } };
    return;
  }
  const a = Object.assign(document.createElement('a'), { href: URL.createObjectURL(blob), download: pdfName(j) });
  document.body.append(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 30_000);
}
export async function sharePdf(j, o) {
  const file = new File([await fetchPdf(j, o)], pdfName(j), { type: 'application/pdf' });
  if (navigator.canShare?.({ files: [file] })) {
    try { await navigator.share({ files: [file], title: `Informe LCC — ${address(j)} (${j.id})` }); } catch (e) { if (e.name !== 'AbortError') throw e; }
  } else await downloadPdf(j, o); // no native share (most desktops): download instead
}
// what goes in the PDF; the PDF for the chosen switches is made while the sheet is open, so the button acts at once
function pdfSheet(j, kind) {
  const o = pdfOpts(), counts = { materials: materialList(j).length, problems: (j.problems || []).length };
  const share = kind === 'share';
  const d = sheet(`<h2>${share ? 'Compartir informe' : 'Descargar PDF'}</h2><p class="muted">Las fotos de antes y después van siempre. Elige qué más incluir:</p>
    <div class="list-card">${PDF_PARTS.map(([k, label, sub]) => `<label class="list-row switch-row"><span class="grow"><b>${label}</b> <span class="muted">(${counts[k]})</span><br><small class="muted">${sub}</small></span>
      <input type="checkbox" role="switch" data-part="${k}" ${o[k] !== false ? 'checked' : ''}><span class="switch" aria-hidden="true"></span></label>`).join('')}</div>
    <div class="sheet-actions"><button class="btn btn-primary btn-lg" data-go>${icon(share ? 'ios_share' : 'download')} ${share ? 'Compartir' : 'Descargar PDF'}</button><button class="btn btn-secondary" data-close>Cancelar</button></div>`);
  const warm = () => fetchPdf(j, o).catch(() => {});
  warm();
  $$('[data-part]', d).forEach((c) => c.addEventListener('change', () => {
    o[c.dataset.part] = c.checked;
    try { localStorage.setItem('lcc-pdf-parts', JSON.stringify(o)); } catch {}
    warm();
  }));
  const go = $('[data-go]', d);
  go.onclick = async () => {
    const label = go.innerHTML;
    go.disabled = true; go.innerHTML = `<span class="spin" aria-hidden="true"></span> Generando…`;
    try { await (share ? sharePdf(j, { ...o }) : downloadPdf(j, { ...o })); d.close(); }
    catch (ex) { toast(ex.offline ? 'Los informes necesitan conexión — inténtalo cuando tengas cobertura' : ex.message, 'bad'); }
    go.disabled = false; go.innerHTML = label;
  };
}
export const pdfActions = (j, small = false) => `
  <button class="btn btn-secondary ${small ? 'btn-sm' : ''}" data-pdf="download" data-job="${esc(j.id)}">${icon('download')} Descargar PDF</button>
  <button class="btn btn-secondary ${small ? 'btn-sm' : ''}" data-pdf="share" data-job="${esc(j.id)}">${icon('ios_share')} Compartir</button>`;
export function wirePdfActions(root) {
  on(root, '[data-pdf]', 'click', (e, b) => {
    const j = store.job(b.dataset.job);
    if (j) pdfSheet(j, b.dataset.pdf);
  });
}

